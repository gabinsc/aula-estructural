import { expect, test } from '@playwright/test'
import type { Locator, Page } from '@playwright/test'

type XY = readonly [x: number, y: number]

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const node = (page: Page, id: string) => page.locator(`[data-node-id="${id}"]`)
const bar = (page: Page, id: string) => page.locator(`[data-bar-id="${id}"]`)
const counts = (page: Page) => page.locator('.model-counts strong')
const group = (page: Page) => page.getByRole('region', { name: 'Propiedades de selección múltiple' })
const properties = (page: Page) => page.locator('.selected-object + .properties')

async function enterPoint(page: Page, [x, y]: XY, confirm: string) {
  await page.getByLabel('X (m)', { exact: true }).fill(String(x))
  await page.getByLabel('Y (m)', { exact: true }).fill(String(y))
  await button(page, confirm).click()
}

async function addNodes(page: Page, points: readonly XY[]) {
  await page.keyboard.press('n')
  for (const point of points) await enterPoint(page, point, 'Crear nudo')
}

async function addBar(page: Page, start: XY, end: XY) {
  await page.keyboard.press('b')
  await enterPoint(page, start, 'Fijar inicio')
  await enterPoint(page, end, 'Crear barra')
}

async function screenPoint(page: Page, [x, y]: XY) {
  const canvas = await page.locator('.model-canvas').boundingBox()
  const axesOrigin = page.locator('.global-origin circle')
  if (!canvas) throw new Error('Lienzo no visible')
  const originX = Number(await axesOrigin.getAttribute('cx'))
  const originY = Number(await axesOrigin.getAttribute('cy'))
  const scale = Number((await page.locator('.status-view output').innerText()).replace(' px/m', '').replace(',', '.'))
  return { x: canvas.x + originX + scale * x, y: canvas.y + originY - scale * y }
}

async function center(locator: Locator) {
  const box = await locator.boundingBox()
  if (!box) throw new Error('Elemento no visible')
  return { x: box.x + box.width / 2, y: box.y + box.height / 2 }
}

async function clickAt(page: Page, position: { x: number; y: number }, modifier?: 'Shift' | 'Control') {
  if (modifier) await page.keyboard.down(modifier)
  try {
    await page.mouse.click(position.x, position.y)
  } finally {
    if (modifier) await page.keyboard.up(modifier)
  }
}

async function pickNode(page: Page, id: string, modifier?: 'Shift' | 'Control') {
  await clickAt(page, await center(node(page, id).locator('.joint-mark')), modifier)
}

async function pickBar(page: Page, id: string, modifier?: 'Shift' | 'Control') {
  await clickAt(page, await center(bar(page, id).locator('.member-line')), modifier)
}

async function windowSelect(page: Page, from: XY, to: XY) {
  const a = await screenPoint(page, from)
  const b = await screenPoint(page, to)
  await page.mouse.move(a.x, a.y)
  await page.mouse.down()
  await page.mouse.move(b.x, b.y, { steps: 4 })
  await page.mouse.up()
}

async function expectNodePosition(page: Page, id: string, x: string, y: string) {
  await pickNode(page, id)
  const coordinates = properties(page).locator('dd')
  await expect(coordinates.nth(0)).toHaveText(`${x} m`)
  await expect(coordinates.nth(1)).toHaveText(`${y} m`)
}

